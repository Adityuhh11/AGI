func TestParseKeepsApplicationsAndDropsTheRestOfTheStartMenu(t *testing.T) {
	got, err := parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	want := "Visual Studio Code|Calculator|7-Zip File Manager|Services|SQL Shell (psql)|Red Dead Redemption 2|Zen"
	if names(got) != want {
		t.Fatalf("kept %s\nwant %s", names(got), want)
	}
}

func TestParseAcceptsOneEntryAndAByteOrderMark(t *testing.T) {
	got, err := parse([]byte("\ufeff" + `{"Name":"Zen","AppID":"F0DC299D809B9700"}`))
	if err != nil || len(got) != 1 || got[0].Name != "Zen" {
		t.Fatalf("parse = %v, %v", got, err)
	}
	if _, err := parse([]byte("not json")); err == nil {
		t.Fatal("a list that is not JSON must be an error")
	}
}
