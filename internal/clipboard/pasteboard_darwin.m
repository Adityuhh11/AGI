static char *copyString(NSString *text) {
	if (text == nil) {
		return NULL;
	}
	const char *utf8 = [text UTF8String];
	return utf8 ? strdup(utf8) : NULL;
}

// AppKit's workspace is read from the main thread.
static void onMain(void (^block)(void)) {
	if ([NSThread isMainThread]) {
		block();
	} else {
		dispatch_sync(dispatch_get_main_queue(), block);
	}
}

long omniPasteboardCount(void) {
	return (long)[[NSPasteboard generalPasteboard] changeCount];
}

char *omniPasteboardString(void) {
	@autoreleasepool {
		return copyString([[NSPasteboard generalPasteboard] stringForType:NSPasteboardTypeString]);
	}
}

// The convention of https://nspasteboard.org: password managers mark what they copy as concealed, programs that copy by themselves
// mark it as auto-generated or transient, and a history is not to keep any of them.
int omniPasteboardPrivate(void) {
	@autoreleasepool {
		NSArray<NSPasteboardType> *types = [[NSPasteboard generalPasteboard] types];
		for (NSString *marker in @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType"]) {
			if ([types containsObject:marker]) {
				return 1;
			}
		}
		return 0;
	}
}

// The frontmost application is read from whichever thread asks: these are called by the watcher every few hundred milliseconds, and a hop to the main
// thread would wait on a run loop that a test binary does not have.
char *omniFrontmostName(void) {
	NSRunningApplication *app = [[NSWorkspace sharedWorkspace] frontmostApplication];
	return copyString(app.localizedName);
}

int omniClipFrontmostPID(void) {
	NSRunningApplication *app = [[NSWorkspace sharedWorkspace] frontmostApplication];
	return app ? app.processIdentifier : 0;
}

int omniSecureInput(void) {
	return IsSecureEventInputEnabled() ? 1 : 0;
}

int omniAccessibilityTrusted(int prompt) {
	NSDictionary *options = @{(__bridge id)kAXTrustedCheckOptionPrompt: @(prompt != 0)};
	return AXIsProcessTrustedWithOptions((__bridge CFDictionaryRef)options) ? 1 : 0;
}

// The key that types "v" on the keyboard layout in use. A shortcut is found by the character, so on a layout where V is not where it is on
// a US keyboard (Dvorak, AZERTY) the physical V key would paste nothing. 9 is V on a US keyboard, used when the layout cannot be read.
static CGKeyCode keyForV(void) {
	TISInputSourceRef source = TISCopyCurrentKeyboardLayoutInputSource();
	if (source == NULL) {
		return 9;
	}
	CFDataRef layoutData = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData);
	CGKeyCode found = 9;
	if (layoutData != NULL) {
		const UCKeyboardLayout *layout = (const UCKeyboardLayout *)CFDataGetBytePtr(layoutData);
		for (CGKeyCode code = 0; code < 128; code++) {
			UInt32 deadKeys = 0;
			UniChar chars[4];
			UniCharCount length = 0;
			OSStatus status = UCKeyTranslate(layout, code, kUCKeyActionDown, 0, LMGetKbdType(), kUCKeyTranslateNoDeadKeysBit, &deadKeys, 4, &length, chars);
			if (status == noErr && length == 1 && chars[0] == 'v') {
				found = code;
				break;
			}
		}
	}
	CFRelease(source);
	return found;
}

int omniSendPaste(void) {
	CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateHIDSystemState);
	// The keyboard layout is read through Text Input Sources, which abort the program when asked from any thread but the main one.
	__block CGKeyCode key = 9;
	onMain(^{ key = keyForV(); });
	CGEventRef down = CGEventCreateKeyboardEvent(source, key, true);
	CGEventRef up = CGEventCreateKeyboardEvent(source, key, false);
	int result = 1;
	if (down != NULL && up != NULL) {
		CGEventSetFlags(down, kCGEventFlagMaskCommand);
		CGEventSetFlags(up, kCGEventFlagMaskCommand);
		CGEventPost(kCGHIDEventTap, down);
		CGEventPost(kCGHIDEventTap, up);
		result = 0;
	}
	if (down != NULL) {
		CFRelease(down);
	}
	if (up != NULL) {
		CFRelease(up);
	}
	if (source != NULL) {
		CFRelease(source);
	}
	return result;
}
